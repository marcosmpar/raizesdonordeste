CREATE TABLE pedidos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id      BIGINT,
    unidade_id      BIGINT        NOT NULL,
    canal_pedido    VARCHAR(10)   NOT NULL,
    status          VARCHAR(25)   NOT NULL,
    forma_pagamento VARCHAR(20)   NOT NULL,
    total           NUMERIC(12, 2) NOT NULL,
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pedidos_cliente FOREIGN KEY (cliente_id) REFERENCES usuarios (id),
    CONSTRAINT fk_pedidos_unidade FOREIGN KEY (unidade_id) REFERENCES unidades (id),
    CONSTRAINT ck_pedidos_canal CHECK (canal_pedido IN ('APP', 'TOTEM', 'BALCAO', 'PICKUP', 'WEB')),
    CONSTRAINT ck_pedidos_status CHECK (status IN ('AGUARDANDO_PAGAMENTO', 'EM_PREPARO', 'PRONTO', 'ENTREGUE', 'CANCELADO')),
    CONSTRAINT ck_pedidos_forma CHECK (forma_pagamento IN ('MOCK', 'PIX', 'CARTAO_CREDITO', 'CARTAO_DEBITO')),
    CONSTRAINT ck_pedidos_total CHECK (total >= 0)
);

CREATE INDEX idx_pedidos_canal ON pedidos (canal_pedido);
CREATE INDEX idx_pedidos_status ON pedidos (status);
CREATE INDEX idx_pedidos_unidade ON pedidos (unidade_id);
CREATE INDEX idx_pedidos_cliente ON pedidos (cliente_id);

-- Preço e nome do produto são copiados para o item (histórico não muda se o catálogo mudar)
CREATE TABLE itens_pedido (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id      BIGINT         NOT NULL,
    produto_id     BIGINT         NOT NULL,
    produto_nome   VARCHAR(120)   NOT NULL,
    quantidade     INTEGER        NOT NULL,
    preco_unitario NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_itens_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id),
    CONSTRAINT fk_itens_produto FOREIGN KEY (produto_id) REFERENCES produtos (id),
    CONSTRAINT ck_itens_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_itens_preco CHECK (preco_unitario > 0)
);

CREATE INDEX idx_itens_pedido ON itens_pedido (pedido_id);

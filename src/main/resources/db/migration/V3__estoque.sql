-- Saldo atual de cada produto em cada unidade (estoque próprio por unidade)
CREATE TABLE estoques (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id BIGINT  NOT NULL,
    produto_id BIGINT  NOT NULL,
    quantidade INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_estoques_unidade FOREIGN KEY (unidade_id) REFERENCES unidades (id),
    CONSTRAINT fk_estoques_produto FOREIGN KEY (produto_id) REFERENCES produtos (id),
    CONSTRAINT uk_estoques_unidade_produto UNIQUE (unidade_id, produto_id),
    CONSTRAINT ck_estoques_quantidade CHECK (quantidade >= 0)
);

-- Livro de movimentações (entrada/saída) para rastreabilidade
CREATE TABLE movimentacoes_estoque (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id BIGINT      NOT NULL,
    produto_id BIGINT      NOT NULL,
    tipo       VARCHAR(10) NOT NULL,
    quantidade INTEGER     NOT NULL,
    motivo     VARCHAR(200),
    usuario_id BIGINT,
    criado_em  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_mov_unidade FOREIGN KEY (unidade_id) REFERENCES unidades (id),
    CONSTRAINT fk_mov_produto FOREIGN KEY (produto_id) REFERENCES produtos (id),
    CONSTRAINT fk_mov_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_mov_tipo CHECK (tipo IN ('ENTRADA', 'SAIDA')),
    CONSTRAINT ck_mov_quantidade CHECK (quantidade > 0)
);

CREATE INDEX idx_mov_unidade_produto ON movimentacoes_estoque (unidade_id, produto_id);

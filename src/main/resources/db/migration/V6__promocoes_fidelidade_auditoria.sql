-- Fidelidade (LGPD: só acumula/resgata com consentimento explícito do cliente)
CREATE TABLE contas_fidelidade (
    usuario_id       BIGINT PRIMARY KEY,
    consentimento    BOOLEAN NOT NULL DEFAULT FALSE,
    consentimento_em TIMESTAMP WITH TIME ZONE,
    revogado_em      TIMESTAMP WITH TIME ZONE,
    saldo_pontos     INTEGER NOT NULL DEFAULT 0,
    criado_em        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_contas_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_contas_saldo CHECK (saldo_pontos >= 0)
);

-- pontos com sinal: ACUMULO (+), RESGATE (-), ESTORNO (+/-)
CREATE TABLE movimentos_pontos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT      NOT NULL,
    tipo       VARCHAR(10) NOT NULL,
    pontos     INTEGER     NOT NULL,
    pedido_id  BIGINT,
    descricao  VARCHAR(200),
    criado_em  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_movpontos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT fk_movpontos_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id),
    CONSTRAINT ck_movpontos_tipo CHECK (tipo IN ('ACUMULO', 'RESGATE', 'ESTORNO'))
);

CREATE INDEX idx_movpontos_usuario ON movimentos_pontos (usuario_id);
CREATE INDEX idx_movpontos_pedido ON movimentos_pontos (pedido_id);

-- Auditoria de ações sensíveis (sem dados pessoais nem segredos)
CREATE TABLE auditoria_logs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ator_id    BIGINT,
    acao       VARCHAR(40) NOT NULL,
    entidade   VARCHAR(40) NOT NULL,
    entidade_id BIGINT,
    detalhes   VARCHAR(500),
    request_id VARCHAR(60),
    criado_em  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_auditoria_entidade ON auditoria_logs (entidade, entidade_id);
CREATE INDEX idx_auditoria_acao ON auditoria_logs (acao);

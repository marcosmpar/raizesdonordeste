-- Promoções / campanhas
CREATE TABLE promocoes (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(30)  NOT NULL,
    descricao           VARCHAR(200) NOT NULL,
    tipo                VARCHAR(12)  NOT NULL,
    valor               NUMERIC(10, 2) NOT NULL,
    valor_minimo_pedido NUMERIC(10, 2),
    unidade_id          BIGINT,
    inicio              TIMESTAMP WITH TIME ZONE NOT NULL,
    fim                 TIMESTAMP WITH TIME ZONE NOT NULL,
    ativa               BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_promocoes_codigo UNIQUE (codigo),
    CONSTRAINT fk_promocoes_unidade FOREIGN KEY (unidade_id) REFERENCES unidades (id),
    CONSTRAINT ck_promocoes_tipo CHECK (tipo IN ('PERCENTUAL', 'VALOR_FIXO')),
    CONSTRAINT ck_promocoes_valor CHECK (valor > 0),
    CONSTRAINT ck_promocoes_periodo CHECK (fim > inicio)
);


CREATE TABLE unidades (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(120) NOT NULL,
    cidade    VARCHAR(80)  NOT NULL,
    uf        VARCHAR(2)   NOT NULL,
    endereco  VARCHAR(200) NOT NULL,
    ativa     BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_unidades_nome UNIQUE (nome)
);

CREATE TABLE produtos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(120) NOT NULL,
    descricao  VARCHAR(300),
    categoria  VARCHAR(60)  NOT NULL,
    preco_base NUMERIC(10, 2) NOT NULL,
    ativo      BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_produtos_nome UNIQUE (nome),
    CONSTRAINT ck_produtos_preco CHECK (preco_base > 0)
);

-- Cardápio por unidade: produto oferecido em uma unidade, com preço e disponibilidade próprios
CREATE TABLE cardapio_itens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    preco      NUMERIC(10, 2) NOT NULL,
    disponivel BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_cardapio_unidade FOREIGN KEY (unidade_id) REFERENCES unidades (id),
    CONSTRAINT fk_cardapio_produto FOREIGN KEY (produto_id) REFERENCES produtos (id),
    CONSTRAINT uk_cardapio_unidade_produto UNIQUE (unidade_id, produto_id),
    CONSTRAINT ck_cardapio_preco CHECK (preco > 0)
);

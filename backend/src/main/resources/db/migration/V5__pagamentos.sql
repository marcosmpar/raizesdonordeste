-- Pagamento desacoplado do pedido: um pedido pode ter várias tentativas (ex.: recusado e depois aprovado)
CREATE TABLE pagamentos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id         BIGINT         NOT NULL,
    status            VARCHAR(12)    NOT NULL,
    valor             NUMERIC(12, 2) NOT NULL,
    forma_pagamento   VARCHAR(20)    NOT NULL,
    chave_idempotencia VARCHAR(80),
    transacao_gateway VARCHAR(60),
    codigo_gateway    VARCHAR(40),
    mensagem          VARCHAR(200),
    criado_em         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pagamentos_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id),
    CONSTRAINT ck_pagamentos_status CHECK (status IN ('PENDENTE', 'APROVADO', 'RECUSADO', 'ESTORNADO')),
    CONSTRAINT ck_pagamentos_forma CHECK (forma_pagamento IN ('MOCK', 'PIX', 'CARTAO_CREDITO', 'CARTAO_DEBITO')),
    CONSTRAINT ck_pagamentos_valor CHECK (valor >= 0),
    CONSTRAINT uk_pagamentos_pedido_chave UNIQUE (pedido_id, chave_idempotencia)
);

CREATE INDEX idx_pagamentos_pedido ON pagamentos (pedido_id);
